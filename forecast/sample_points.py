"""Regenerate data/sample_points.json from EIA's operating-generator inventory (replaces the hand-picked points, FM2):
python -m forecast.sample_points. Plants of one fuel in one grid are clustered by location, weighted by nameplate MW;
each cluster becomes a weather point weighted by its share of capacity."""
import json
import os

import numpy as np
import pandas as pd
import requests
from sklearn.cluster import KMeans

from pipeline import store

U = "https://api.eia.gov/v2/electricity/operating-generator-capacity/data/"
TECH = {"SUN": "Solar Photovoltaic", "WND": "Onshore Wind Turbine"}
TARGETS = {"SRP": ["SUN"], "PACE": ["SUN", "WND"], "SOCO": ["SUN"]}  # FB11 build order
K = 6


def _get(params):
    r = requests.get(U, params=params, timeout=60)
    try:
        r.raise_for_status()
    except requests.RequestException as e:
        raise RuntimeError(f"EIA generator inventory failed (status {r.status_code})") from None  # no URL: it holds the key
    return r.json()["response"]["data"]


def plants(key, eia_code, tech, period):
    rows, off = [], 0
    while True:
        d = _get([("api_key", key), ("data[0]", "nameplate-capacity-mw"), ("data[1]", "latitude"), ("data[2]", "longitude"),
                  ("start", period), ("end", period), ("facets[balancing_authority_code][]", eia_code), ("facets[technology][]", tech),
                  ("facets[status][]", "OP"), ("length", 5000), ("offset", off)])
        rows += d
        if len(d) < 5000:
            break
        off += 5000
    df = pd.DataFrame(rows)
    df["mw"] = df["nameplate-capacity-mw"].astype(float)
    return df.groupby("plantid").agg(lat=("latitude", "first"), lon=("longitude", "first"), mw=("mw", "sum")).astype(float).reset_index()


def main():
    key = os.environ["EIA_API_KEY"]
    reg = {g["id"]: g["eia_code"] for g in json.load(open(os.path.join(store.ROOT, "data", "hubs.json")))["grids"]}
    period = _get([("api_key", key), ("data[0]", "nameplate-capacity-mw"), ("sort[0][column]", "period"), ("sort[0][direction]", "desc"), ("length", 1)])[0]["period"]
    out = {"_note": f"Generated by forecast/sample_points.py from EIA-860M operating plants, period {period}. Points are capacity-weighted clusters of plant locations (FM2).",
           "model": "gfs_seamless", "grids": {}}
    for grid, fuels in TARGETS.items():
        out["grids"][grid] = {}
        for fuel in fuels:
            df = plants(key, reg[grid], TECH[fuel], period)
            km = KMeans(n_clusters=min(K, len(df)), n_init=10, random_state=0).fit(df[["lat", "lon"]], sample_weight=df["mw"])
            pts = []
            for c in range(km.n_clusters):
                m = df[km.labels_ == c]
                pts.append({"id": f"{fuel.lower()}{c}", "lat": round(float(np.average(m.lat, weights=m.mw)), 2),
                            "lon": round(float(np.average(m.lon, weights=m.mw)), 2), "weight": round(float(m.mw.sum() / df.mw.sum()), 4)})
            out["grids"][grid][fuel] = {"points": pts, "plants": len(df), "mw": round(float(df.mw.sum()))}
            print(grid, fuel, len(df), "plants", round(df.mw.sum()), "MW ->", [(p["id"], p["lat"], p["lon"], p["weight"]) for p in pts])
    json.dump(out, open(os.path.join(store.ROOT, "data", "sample_points.json"), "w"), indent=1)


if __name__ == "__main__":
    main()
